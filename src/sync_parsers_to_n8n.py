"""
Sync src/parse_*.py into the matching n8n Code nodes.

There are deliberately two copies of every parser: the standalone module in src/
(used by the notebooks and by the mass-ingestion backfill script) and a copy pasted
inside an n8n Code node (used by the live webhook/form/folder-watcher pipeline).
They must stay identical, and hand-copying them is exactly how they drifted apart
before - the n8n copy of the microscopy parser silently stayed on an old version
that had no JEOL sidecar support and no TEM filename-magnification fallback.

This script regenerates each n8n node's Python from the src/ module, which is the
single source of truth, and pushes it through the n8n REST API.

The generated node code is: the whole src module (its docstring stripped, since a
Code node has no use for it), plus a preamble that materialises the uploaded file
from the base64 field the pipeline carries, plus an epilogue that copies the parsed
result onto the n8n item.

Usage:
    python src/sync_parsers_to_n8n.py            # push all parsers
    python src/sync_parsers_to_n8n.py --dry-run  # print what would change
"""

import os
import re
import sys
import json
import argparse
import urllib.request

SRC_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.dirname(SRC_DIR)

WORKFLOW_ID = '6p4lEVEe8rwUgEkO'
N8N_BASE = os.environ.get('N8N_BASE_URL', 'http://localhost:5678')

# node name -> (src module file, parser function, technique used for the staging path)
PARSER_NODES = {
    'Parse PXRD (.xrdml)':    ('parse_pxrd_xrdml.py',      'parse_pxrd_xrdml',      'PXRD'),
    'Parse VT-XRD (.brml)':   ('parse_vtxrd_brml.py',      'parse_bruker_brml',     'VT-XRD'),
    'Parse TGA (.txt)':       ('parse_tga_txt.py',         'parse_tga_txt',         'TGA'),
    'Parse FTIR (.csv)':      ('parse_ftir_csv.py',        'parse_ftir_csv',        'FTIR'),
    'Parse Adsorption (.xls)': ('parse_adsorption_xls.py', 'parse_bet_xls',         'ADSORPTION'),
    'Parse UV-Vis (.asc)':    ('parse_uvvis_asc.py',       'parse_uvvis_asc',       'UV_VIS'),
    'Parse Microscopy (.jpg)': ('parse_microscopy_image.py', 'parse_microscopy_image', 'SEM'),
}

PREAMBLE = '''

# ---------------------------------------------------------------------------
# n8n glue (generated by src/sync_parsers_to_n8n.py - do not edit in the n8n UI,
# edit src/{src_file} instead and re-run the sync script).
# ---------------------------------------------------------------------------
import base64

b64_data = _item['json'].get('data_file_base64')

if b64_data:
    original_name = _item['json'].get('file_name') or 'upload'
    technique_for_path = (_item['json'].get('technique') or '{technique}').upper()
    hash_prefix = (_item['json'].get('file_hash') or 'nohash')[:8]
    target_dir = os.path.join('/home/node/data/raw_datalake', technique_for_path)
    os.makedirs(target_dir, exist_ok=True)
    target_path = os.path.join(target_dir, hash_prefix + '_' + original_name)
    with open(target_path, 'wb') as _f:
        _f.write(base64.b64decode(b64_data))
    file_path = target_path
    _item['json']['raw_file_path'] = target_path
    _item['json']['file_name'] = os.path.basename(target_path)
else:
    file_path = _item['json'].get('raw_file_path')

sample_code = _item['json'].get('sample_code')
'''

EPILOGUE = '''
_item['json']['sample_code'] = result['sample_code']
_item['json']['technique'] = result['technique']
_item['json']['measurement_tag'] = result['measurement_tag']
_item['json']['operator_name'] = result.get('operator_name') or _item['json'].get('operator_name')
_item['json']['instrument_name'] = result['instrument_name']
_item['json']['file_name'] = result['file_name']
_item['json']['raw_file_path'] = result['raw_file_path']
_item['json']['data_json'] = result['data_json']

return _item
'''


def strip_module_docstring(source):
    """Remove the leading triple-quoted module docstring (a Code node has no use for it)."""
    stripped = source.lstrip()
    if stripped.startswith('"""'):
        end = stripped.find('"""', 3)
        if end != -1:
            return stripped[end + 3:].lstrip('\n')
    return source


def build_node_code(node_name):
    src_file, fn_name, technique = PARSER_NODES[node_name]
    with open(os.path.join(SRC_DIR, src_file), 'r', encoding='utf-8') as f:
        body = strip_module_docstring(f.read())

    preamble = PREAMBLE.format(src_file=src_file, technique=technique)

    if fn_name == 'parse_microscopy_image':
        # Microscopy needs the technique (SEM/FESEM/TEM all share one parser) and the
        # path of the companion metadata file, which an earlier node already wrote to
        # disk from its own binary - see 'Write Metadata File to Disk'.
        call = (
            "\ntechnique = _item['json'].get('technique')\n"
            "result = parse_microscopy_image(\n"
            "    file_path,\n"
            "    sample_code=sample_code,\n"
            "    technique=technique,\n"
            "    metadata_txt_path=_item['json'].get('instrument_metadata_written_path'),\n"
            ")\n"
        )
    else:
        call = "\nresult = %s(file_path, sample_code=sample_code)\n" % fn_name

    return body + preamble + call + EPILOGUE


def n8n_request(method, path, payload=None):
    api_key = os.environ.get('N8N_API_KEY')
    if not api_key:
        # Fall back to reading it out of .env (gitignored) so the script works with no setup.
        env_path = os.path.join(ROOT_DIR, '.env')
        if os.path.exists(env_path):
            with open(env_path, 'r', encoding='utf-8') as f:
                for line in f:
                    if line.startswith('N8N_API_KEY='):
                        api_key = line.split('=', 1)[1].strip()
                        break
    if not api_key:
        raise SystemExit('N8N_API_KEY not found in the environment or in .env')

    url = N8N_BASE.rstrip('/') + path
    data = json.dumps(payload).encode('utf-8') if payload is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header('X-N8N-API-KEY', api_key)
    req.add_header('Content-Type', 'application/json')
    with urllib.request.urlopen(req) as resp:
        return json.loads(resp.read().decode('utf-8'))


def main():
    cli = argparse.ArgumentParser(description='Sync src/parse_*.py into the n8n Code nodes')
    cli.add_argument('--dry-run', action='store_true', help='Report differences without pushing')
    cli.add_argument('--node', action='append', choices=sorted(PARSER_NODES),
                     help='Limit to one node; repeat the flag for several. Default: all.')
    args = cli.parse_args()

    targets = args.node or sorted(PARSER_NODES)

    workflow = n8n_request('GET', '/api/v1/workflows/' + WORKFLOW_ID)
    nodes = workflow['nodes']
    by_name = {n['name']: n for n in nodes}

    changed = []
    for node_name in targets:
        if node_name not in by_name:
            print('[%s] NOT FOUND in the workflow - skipped' % node_name)
            continue
        new_code = build_node_code(node_name)
        current = by_name[node_name]['parameters'].get('pythonCode', '')
        if current == new_code:
            print('[%s] already in sync' % node_name)
            continue
        changed.append(node_name)
        print('[%s] OUT OF SYNC (%d -> %d chars)' % (node_name, len(current), len(new_code)))
        if not args.dry_run:
            by_name[node_name]['parameters']['pythonCode'] = new_code

    if args.dry_run:
        print('\n(DRY RUN - nothing pushed)')
        return

    if not changed:
        print('\nEverything already in sync, nothing to push.')
        return

    # The n8n REST API rejects read-only fields on PUT, so send only what it accepts.
    # It also rejects settings keys it does not declare in its own schema (the live
    # workflow carries UI-only extras like binaryMode/availableInMCP), so whitelist them.
    allowed_settings = {
        'executionOrder', 'saveDataErrorExecution', 'saveDataSuccessExecution',
        'saveManualExecutions', 'saveExecutionProgress', 'executionTimeout',
        'errorWorkflow', 'timezone',
    }
    settings = {k: v for k, v in (workflow.get('settings') or {}).items() if k in allowed_settings}
    payload = {
        'name': workflow['name'],
        'nodes': nodes,
        'connections': workflow['connections'],
        'settings': settings,
    }
    n8n_request('PUT', '/api/v1/workflows/' + WORKFLOW_ID, payload)
    print('\nPushed %d node(s): %s' % (len(changed), ', '.join(changed)))


if __name__ == '__main__':
    main()
